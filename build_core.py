#!/usr/bin/env python3
"""Build Lab's Blockly core locally with the pinned compiler and Closure archive."""

import argparse
import hashlib
import os
from pathlib import Path
import re
import subprocess
import tarfile
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler-jar', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--java', default=str(Path(os.environ['JAVA_HOME']) / 'bin/java')
                        if os.environ.get('JAVA_HOME') else 'java')
    args = parser.parse_args()
    source = Path(__file__).resolve().parent
    compiler = args.compiler_jar.resolve(strict=True)
    output = args.output.resolve()
    version = subprocess.run([args.java, '-jar', str(compiler), '--version'],
                             check=True, capture_output=True, text=True)
    if not re.search(r'\b[vV]20200719\b', version.stdout + version.stderr):
        parser.error('Use google-closure-compiler-java 20200719.0.0.')

    archive = source / 'z-Docker/closure-library.tgz'
    patch = source / 'z-Docker/closure-library-openroberta.patch'
    with tempfile.TemporaryDirectory(prefix='blockly-core-') as directory:
        work = Path(directory)
        with tarfile.open(archive) as bundle:
            bundle.extractall(work, filter='data')
        closure = work / 'closure-library'
        subprocess.run(['patch', '--batch', '--fuzz=0', '-p1', '-i', str(patch)],
                       cwd=closure, check=True)
        raw_output = work / 'compiled.js'
        subprocess.run([
            args.java, '-jar', str(compiler),
            '--js=' + str(closure / 'closure/goog/**.js'),
            '--js=blocks/**.js', '--js=core/**.js', '--js=msg/js/**.js',
            '--generate_exports', '--warning_level=QUIET',
            '--compilation_level=SIMPLE_OPTIMIZATIONS', '--entry_point=Blockly',
            '--js_output_file=' + str(raw_output),
        ], cwd=source, check=True)
        # Match build.py's header and license shortening; keep runtime bytes
        # entirely compiler-generated. Translations are not regenerated here.
        code = "// Do not edit this file; automatically generated by build_core.py.\n'use strict';\n\n"
        code += raw_output.read_text(encoding='utf-8')
        license_pattern = re.compile(
            r'/\*\n\n [\w ]+\n\n (Copyright \d+ Google Inc\.)\n'
            r' https://developers\.google\.com/blockly/\n\n'
            r' Licensed under the Apache License, Version 2\.0 \(the "License"\);\n'
            r' you may not use this file except in compliance with the License\.\n'
            r' You may obtain a copy of the License at\n\n'
            r'   http://www\.apache\.org/licenses/LICENSE-2\.0\n\n'
            r' Unless required by applicable law or agreed to in writing, software\n'
            r' distributed under the License is distributed on an "AS IS" BASIS,\n'
            r' WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied\.\n'
            r' See the License for the specific language governing permissions and\n'
            r' limitations under the License\.\n\*/')
        code = license_pattern.sub(r'\n// \1  Apache License 2.0', code)
        output.write_text(code, encoding='utf-8')
    for name, path in [('Closure archive', archive), ('Compiler JAR', compiler), ('Output', output)]:
        print(name + ' SHA-256: ' + hashlib.sha256(path.read_bytes()).hexdigest())


if __name__ == '__main__':
    main()
